-- 1. CREAR TABLA DE RECETAS

CREATE TABLE IF NOT EXISTS public.recetas (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(100) NOT NULL,

    categoria VARCHAR(30) NOT NULL
        CHECK (
            categoria IN (
                'Comidas',
                'Postres',
                'Desayunos',
                'Bebidas'
            )
        ),

    ingredientes TEXT NOT NULL,

    preparacion TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()

);


-- =========================================
-- 2. ACTIVAR SEGURIDAD DE LA TABLA
-- =========================================

ALTER TABLE public.recetas
ENABLE ROW LEVEL SECURITY;


-- =========================================
-- 3. CONFIGURAR PERMISOS
-- =========================================

REVOKE ALL ON TABLE public.recetas
FROM anon, authenticated;


-- Permitir consultar recetas

GRANT SELECT ON TABLE public.recetas
TO anon, authenticated;


-- Permitir agregar recetas

GRANT INSERT ON TABLE public.recetas
TO anon, authenticated;


-- Permitir utilizar el identificador automático

GRANT USAGE, SELECT ON SEQUENCE public.recetas_id_seq
TO anon, authenticated;


-- =========================================
-- 4. ELIMINAR POLÍTICAS ANTERIORES
-- =========================================

DROP POLICY IF EXISTS
"Las recetas son visibles para todos"
ON public.recetas;


DROP POLICY IF EXISTS
"Cualquier visitante puede agregar recetas"
ON public.recetas;


-- =========================================
-- 5. POLÍTICA PARA CONSULTAR RECETAS
-- =========================================

CREATE POLICY "Las recetas son visibles para todos"

ON public.recetas

FOR SELECT

TO anon, authenticated

USING (true);


-- =========================================
-- 6. POLÍTICA PARA AGREGAR RECETAS
-- =========================================

CREATE POLICY "Cualquier visitante puede agregar recetas"

ON public.recetas

FOR INSERT

TO anon, authenticated

WITH CHECK (

    CHAR_LENGTH(TRIM(nombre)) BETWEEN 1 AND 100

    AND CHAR_LENGTH(TRIM(ingredientes)) > 0

    AND CHAR_LENGTH(TRIM(preparacion)) > 0

    AND categoria IN (
        'Comidas',
        'Postres',
        'Desayunos',
        'Bebidas'
    )

);


